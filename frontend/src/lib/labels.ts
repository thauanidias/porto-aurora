export function date(value: unknown) {
  if (!value) return "—";
  const d = new Date(String(value));
  return Number.isNaN(d.valueOf())
    ? String(value)
    : new Intl.DateTimeFormat("pt-BR", {
        dateStyle: "short",
        timeStyle: "short",
        timeZone: localStorage.getItem("tgpm_timezone") || "America/Belem",
      }).format(d);
}
